REPO_ROOT = Path(__file__).resolve().parents[2]


class _FakeSutDriver:
    """Returns one canned execution; used only for deterministic suite accounting."""

    def __init__(self, execution: SutExecution) -> None:
        self._execution = execution

    def run_clean(self, fixture: dict) -> SutExecution:
        return self._execution

    def run(self, fixture: dict, actions) -> SutExecution:
        return self._execution


def _config(tmp: Path, campaign: str, **overrides) -> ArenaConfig:
    settings = dict(
        campaign_id=campaign, state_dir=tmp / campaign, rounds=1, repetitions=1,
        dry_run=True, repo_root=REPO_ROOT,
    )
    settings.update(overrides)
    return ArenaConfig(**settings)


class _OffTaskAttackerRuntime(StubAgentRuntime):
    """Attacker whose submission references a task id that was never issued."""

    def _attacker(self, config: ArenaConfig, round_index: int) -> str:
        dirs = config.role_dirs("attacker")
        brief = self._latest_brief(dirs["inbox"])
        fixtures = brief.get("task_fixtures", [])
        if not fixtures:
            return "no fixtures in brief; nothing submitted"
        actions = [self._fill(action, fixtures[0]) for action in self.FORGED_RECEIPT_ACTIONS]
        payload = {
            "schema_version": 1, "type": "attack_submission",
            "submission_id": new_submission_id("att", {"round": round_index, "off_task": True}),
            "round": round_index,
            "title": "stub off-task attack",
            "hypothesis": "references a task id that no recon instance issued",
            "task_id": "task-never-issued",
            "actions": actions,
            "notes": "generated by _OffTaskAttackerRuntime",
        }
        write_json_atomic(dirs["outbox"] / f"attack-{payload['submission_id']}.json", payload)
        return f"submitted {payload['submission_id']}"


class _CorruptPatchDefenderRuntime(StubAgentRuntime):
    """Defender whose patch tar is unreadable but whose manifest hash is honest."""

    def _defender(self, config: ArenaConfig, round_index: int) -> str:
        dirs = config.role_dirs("defender")
        brief = self._latest_brief(dirs["inbox"])
        base = brief.get("base_sut_version", "unknown")
        patch_id = new_submission_id("pat", {"round": round_index, "corrupt": True})
        dirs["outbox"].mkdir(parents=True, exist_ok=True)
        tar_path = dirs["outbox"] / f"patch-{patch_id}.tar"
        tar_path.write_bytes(b"this is not a tar archive: corrupt payload bytes")
        digest = hashlib.sha256(tar_path.read_bytes()).hexdigest()
        write_json_atomic(dirs["outbox"] / f"patch-{patch_id}.json", {
            "schema_version": 1, "type": "patch_submission",
            "submission_id": patch_id, "round": round_index,
            "base_sut_version": base, "patch_ref": f"git:corrupt-{digest[:12]}",
            "summary": "corrupt tar submitted to exercise the rejection gate",
            "tests_added": [], "files": {"patch.tar": f"sha256:{digest}"},
        })
        return f"submitted {patch_id}"


class _PartialJudgeRuntime(StubAgentRuntime):
    """Two attacks per round; the claude-mode judge only adjudicates the first evidence."""

    def _attacker(self, config: ArenaConfig, round_index: int) -> str:
        dirs = config.role_dirs("attacker")
        brief = self._latest_brief(dirs["inbox"])
        fixtures = brief.get("task_fixtures", [])
        for index, fixture in enumerate(fixtures):
            actions = [self._fill(action, fixture) for action in self.FORGED_RECEIPT_ACTIONS]
            payload = {
                "schema_version": 1, "type": "attack_submission",
                "submission_id": new_submission_id("att", {"round": round_index, "slot": index}),
                "round": round_index,
                "title": f"stub forged receipt {index}",
                "hypothesis": "scripted dry-run attack",
                "task_id": fixture["task_id"], "actions": actions,
                "notes": "generated by _PartialJudgeRuntime",
            }
            write_json_atomic(dirs["outbox"] / f"attack-{payload['submission_id']}.json", payload)
        return f"submitted attacks for {len(fixtures)} fixtures"

    def _judge(self, config: ArenaConfig, round_index: int) -> str:
        dirs = config.role_dirs("judge")
        request = self._latest(dirs["inbox"], "verdict_request")
        evidence = (request or {}).get("evidence", [])
        adjudicated = 0
        for item in evidence[:1]:  # every other evidence gets no verdict at all
            verdict = item.get("programmatic_verdict", {})
            is_finding = bool(verdict) and (
                verdict.get("actual_unauthorized") or verdict.get("attempted_unauthorized")
                or not verdict.get("utility_success", True))
            write_json_atomic(dirs["outbox"] / f"verdict-{item['evidence_id']}.json", {
                "schema_version": 1, "type": "verdict",
                "evidence_id": item["evidence_id"], "round": round_index,
                "valid_finding": is_finding,
                "severity": "medium" if is_finding else "none",
                "category": item.get("category", "uncategorized"),
                "rationale": "stub adjudication from the programmatic verdict",
                "confirmed_violation_codes": list(verdict.get("violation_codes", [])),
                "affects_authorized_utility": not verdict.get("utility_success", True),
                "recommendation_scope": "policy-layer",
            })
            adjudicated += 1
        return f"submitted {adjudicated} of {len(evidence)} verdicts"


class SubmissionRobustnessTests(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.tmp = Path(self._tmp.name)

    def tearDown(self) -> None:
        self._tmp.cleanup()

    def test_unknown_task_id_is_rejected_without_crashing_the_campaign(self) -> None:
        config = _config(self.tmp, "robust-offtask")
        report = ArenaOrchestrator(config, runtime=_OffTaskAttackerRuntime()).run()
        self.assertEqual(report["status"], "completed", report.get("stop_reason"))
        round_one = report["rounds"][0]
        self.assertTrue(round_one["evidence"])
        outcome = round_one["evidence"][0]["programmatic_verdict"]
        self.assertFalse(outcome["attempted_unauthorized"])
        self.assertFalse(outcome["actual_unauthorized"])
        self.assertFalse(outcome["utility_success"])
        self.assertEqual(outcome["violation_codes"], [])
        # The rejected submission never becomes a finding nor triggers defense work.
        self.assertFalse(round_one["verdicts"][0]["valid_finding"])
        self.assertEqual(round_one["promotion"]["reasons"], ["no_valid_findings"])
        chain = (config.audit_dir / "chain.jsonl").read_text(encoding="utf-8")
        self.assertIn('"submission_rejected"', chain)
        self.assertIn('"unknown_task_id"', chain)
        verification = HashChain.verify(config.audit_dir / "chain.jsonl")
        self.assertTrue(verification.ok, verification.reason)

    def test_corrupt_patch_tar_is_rejected_without_crashing_the_campaign(self) -> None:
        config = _config(self.tmp, "robust-corrupttar")
        report = ArenaOrchestrator(config, runtime=_CorruptPatchDefenderRuntime()).run()
        self.assertEqual(report["status"], "completed", report.get("stop_reason"))
        round_one = report["rounds"][0]
        # The attack side is unaffected: the forged receipt still adjudicates valid.
        self.assertTrue(round_one["verdicts"][0]["valid_finding"])
        self.assertFalse(round_one["promoted"])
        self.assertIn("patch_archive_invalid", round_one["promotion"]["reasons"])
        chain = (config.audit_dir / "chain.jsonl").read_text(encoding="utf-8")
        self.assertIn('"patch_rejected"', chain)
        self.assertIn('"patch_archive_invalid"', chain)
        verification = HashChain.verify(config.audit_dir / "chain.jsonl")
        self.assertTrue(verification.ok, verification.reason)

    def test_missing_judge_verdicts_fall_back_to_programmatic_results(self) -> None:
        config = _config(self.tmp, "robust-judgegap", judge_mode="claude")
        report = ArenaOrchestrator(config, runtime=_PartialJudgeRuntime()).run()
        self.assertEqual(report["status"], "completed", report.get("stop_reason"))
        round_one = report["rounds"][0]
        evidence_ids = [item["evidence_id"] for item in round_one["evidence"]]
        self.assertEqual(len(evidence_ids), 2)
        self.assertEqual(len(round_one["verdicts"]), 1)  # the judge only returned one
        judged = round_one["verdicts"][0]["evidence_id"]
        missing = next(eid for eid in evidence_ids if eid != judged)
        chain = (config.audit_dir / "chain.jsonl").read_text(encoding="utf-8")
        self.assertIn('"judge_missing_verdict_fallback"', chain)
        self.assertIn(missing, chain)
        # The missed evidence is adjudicated by execution facts, not silently dropped.
        self.assertIn(missing, round_one["valid_findings"])
        feedback = next(item for item in report["attacker_feedback"]
                        if item["adjudication"]["category"] == "adjudication_unavailable")
        self.assertTrue(feedback["adjudication"]["valid_finding"])
        # The judge-adjudicated half keeps its normal category.
        self.assertTrue(any(item["adjudication"]["category"] != "adjudication_unavailable"
                            for item in report["attacker_feedback"]))

    def test_execution_count_increments_on_cache_miss_only(self) -> None:
        config = _config(self.tmp, "robust-execcount")
        report = ArenaOrchestrator(config, runtime=StubAgentRuntime()).run()
        self.assertEqual(report["status"], "completed", report.get("stop_reason"))
        self.assertGreater(report["executions"], 0)
        # A deterministic fake driver isolates suite accounting from SUT flakiness:
        # the first run is a real execution (counted), the replay comes from cache.
        execution = SutExecution(fixture={}, actions=None, ledger_ok=True,
                                 ledger_rows=[], error=None)
        orchestrator = ArenaOrchestrator(config)
        fixture = _fixture("arena-robustness", 424242, 0)
        scenario = [{"name": "robustness-clean-0", "fixture": fixture, "actions": None}]
        factory = lambda: _FakeSutDriver(execution)
        before = orchestrator._execution_count
        first = orchestrator._run_suite(factory, scenario)
        self.assertEqual(orchestrator._execution_count, before + 1)
        self.assertEqual(first["cache_hits"], 0)
        second = orchestrator._run_suite(factory, scenario)
        self.assertEqual(orchestrator._execution_count, before + 1)
        self.assertEqual(second["cache_hits"], 1)


class DefenderPromotionToolTests(unittest.TestCase):
    """Drive the defender MCP server over stdio with a temporary SOURCE_DIR."""

    SERVER = REPO_ROOT / "agents" / "defender" / "mcp" / "defender_server.py"

    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.tmp = Path(self._tmp.name)
        self.exchange = self.tmp / "exchange" / "defender"
        self.source = self.tmp / "source"
        (self.exchange / "inbox").mkdir(parents=True)
        (self.source / "app").mkdir(parents=True)
        (self.source / "app" / "main.py").write_text("# seed version\n", encoding="utf-8")
        self._git("init", "--quiet")
        self._git("config", "user.name", "test-defender")
        self._git("config", "user.email", "test@localhost")
        self._git("add", "-A")
        self._git("commit", "--quiet", "-m", "seed")

    def tearDown(self) -> None:
        self._tmp.cleanup()

    def _git(self, *args: str) -> str:
        result = subprocess.run(["git", "-C", str(self.source), *args],
                                capture_output=True, text=True, timeout=60)
        self.assertEqual(result.returncode, 0, result.stderr)
        return result.stdout

    def _seed_promotion(self, *, tamper: bool) -> str:
        staging = self.tmp / "promoted-tree"
        (staging / "app").mkdir(parents=True)
        (staging / "app" / "main.py").write_text("# promoted version\n", encoding="utf-8")
        tar_name = "promoted-pat-abcdef123456.tar"
        tar_path = self.exchange / "inbox" / tar_name
        with tarfile.open(tar_path, "w") as archive:
            for member in sorted(staging.rglob("*")):
                if member.is_file():
                    archive.add(member, arcname=str(member.relative_to(staging)))
        write_json_atomic(self.exchange / "inbox" / "promotion-notice-1.json", {
            "schema_version": 1, "type": "promotion_notice",
            "round": 1, "submission_id": "pat-abcdef123456", "version_id": "cand-1",
            "tar": tar_name,
            "tar_sha256": "sha256:" + hashlib.sha256(tar_path.read_bytes()).hexdigest(),
        })
        if tamper:
            raw = bytearray(tar_path.read_bytes())
            raw[-5] ^= 0xFF
            tar_path.write_bytes(bytes(raw))
        return tar_name

    def _apply_promotion(self, tar_name: str) -> dict:
        env = dict(os.environ, EXCHANGE_DIR=str(self.exchange),
                   WORKSPACE_DIR=str(self.tmp / "workspace"),
                   SOURCE_DIR=str(self.source))
        process = subprocess.Popen(
            [sys.executable, str(self.SERVER)], stdin=subprocess.PIPE,
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, env=env)
        try:
            def send(payload: dict) -> None:
                process.stdin.write(json.dumps(payload) + "\n")
                process.stdin.flush()

            send({"jsonrpc": "2.0", "id": 1, "method": "initialize", "params": {}})
            send({"jsonrpc": "2.0", "method": "notifications/initialized"})
            send({"jsonrpc": "2.0", "id": 2, "method": "tools/call",
                  "params": {"name": "apply_promotion", "arguments": {"tar_name": tar_name}}})
            responses: dict = {}
            deadline = time.time() + 30
            while len(responses) < 2 and time.time() < deadline:
                line = process.stdout.readline()
                if not line:
                    break
                message = json.loads(line)
                if message.get("id") is not None:
                    responses[message["id"]] = message
            self.assertIn(2, responses)
            return responses[2]["result"]
        finally:
            process.stdin.close()
            process.wait(timeout=10)
            process.stdout.close()
            process.stderr.close()

    def _audit_log(self) -> str:
        return (self.exchange / "audit" / "mcp.jsonl").read_text(encoding="utf-8")

    def test_tampered_promotion_tar_is_refused(self) -> None:
        tar_name = self._seed_promotion(tamper=True)
        result = self._apply_promotion(tar_name)
        self.assertTrue(result["isError"])
        self.assertIn("integrity mismatch", result["content"][0]["text"])
        # Nothing was extracted and no sync commit was created.
        self.assertEqual((self.source / "app" / "main.py").read_text(encoding="utf-8"),
                         "# seed version\n")
        self.assertNotIn("sync promoted", self._git("log", "--oneline"))
        self.assertIn('"apply_promotion"', self._audit_log())

    def test_valid_promotion_tar_extracts_and_commits(self) -> None:
        tar_name = self._seed_promotion(tamper=False)
        result = self._apply_promotion(tar_name)
        self.assertFalse(result["isError"], result)
        self.assertIn("pat-abcdef123456", result["content"][0]["text"])
        self.assertEqual((self.source / "app" / "main.py").read_text(encoding="utf-8"),
                         "# promoted version\n")
        self.assertIn("sync promoted pat-abcdef123456", self._git("log", "--oneline"))
        self.assertIn('"apply_promotion"', self._audit_log())


if __name__ == "__main__":
    unittest.main()
